// Writes netlify.toml: redirects (known SPA routes → index.html 200, everything else → 404),
// security headers and caching. Run from the project root.
const fs = require('fs');

const ROUTES = [
  '/about', '/services', '/training', '/news', '/news/*', '/contact', '/privacy',
  '/sectors/renewable-energy', '/sectors/power-grids-telecom', '/sectors/construction-surveying',
  '/sectors/infrastructure-industry', '/sectors/security-public-safety', '/sectors/environmental-monitoring',
];
const R2 = 'https://pub-8d398fd9e3a643679e74a0eacc815464.r2.dev';
const MEDIA = 'https://media.aerata.com';

const csp = [
  "default-src 'self'",
  `script-src 'self' https://www.googletagmanager.com https://js-eu1.hs-scripts.com https://js-eu1.hs-analytics.net https://js-eu1.hs-banner.com https://js-eu1.hscollectedforms.net https://js-eu1.usemessages.com https://js-eu1.hsadspixel.net https://js-eu1.hsforms.net https://static.hsappstatic.net https://www.google.com/recaptcha/ https://www.gstatic.com/recaptcha/ https://googleads.g.doubleclick.net https://www.googleadservices.com`,
  `style-src 'self' 'unsafe-inline' https://static.hsappstatic.net https://www.gstatic.com/recaptcha/`,
  `font-src 'self' data:`,
  `img-src 'self' data: blob: ${R2} ${MEDIA} https://media.base44.com https://*.hubspot.com https://*.hsforms.com https://*.google-analytics.com https://www.googletagmanager.com https://www.google.com https://www.google.nl https://www.google.gr https://www.gstatic.com https://*.doubleclick.net https://www.googleadservices.com`,
  `media-src 'self' blob: ${R2} ${MEDIA}`,
  `connect-src 'self' https://*.google-analytics.com https://*.analytics.google.com https://www.googletagmanager.com https://www.google.com https://www.google.nl https://www.google.gr https://*.doubleclick.net https://*.hubspot.com wss://*.hubspot.com https://*.hubapi.com https://*.hsforms.com https://*.hscollectedforms.net https://*.hs-banner.com https://*.hs-analytics.net https://*.usemessages.com ${R2} ${MEDIA}`,
  `frame-src https://www.google.com https://*.hubspot.com https://*.hsforms.com https://*.hsforms.net`,
  `worker-src 'self' blob: https://www.google.com/recaptcha/`,
  "manifest-src 'self'",
  "form-action 'self' https://*.hsforms.com https://*.hubspot.com",
  "frame-ancestors 'self'",
  "base-uri 'self'",
  "object-src 'none'",
  'upgrade-insecure-requests',
].join('; ');

const rewrites = ['', '/nl', '/el'].flatMap((pre) => [
  ...(pre ? [pre] : []),
  ...ROUTES.map((r) => pre + r),
]).map((from) => `[[redirects]]\n  from = "${from}"\n  to = "/index.html"\n  status = 200\n`).join('\n');

const toml = `[build]
  command = "npm run build"
  publish = "dist"

# ── Redirects ────────────────────────────────────────────────────────────────
# Netlify reads public/_redirects (old /services/* URLs → 301) before these.
# Generated by scripts/generate-netlify.cjs: edit ROUTES there when pages change.

# www → non-www (canonical domain)
[[redirects]]
  from = "https://www.aerata.com/*"
  to = "https://aerata.com/:splat"
  status = 301
  force = true

[[redirects]]
  from = "https://www.aerata.gr/*"
  to = "https://aerata.gr/:splat"
  status = 301
  force = true

# aerata.gr serves its own robots.txt (force: the static /robots.txt exists).
[[redirects]]
  from = "/robots.txt"
  to = "/robots-gr.txt"
  status = 200
  force = true
  conditions = {Host = ["aerata.gr", "www.aerata.gr"]}

# Known app routes (all languages) render the SPA with status 200.
${rewrites}
# The client portal is a placeholder: render it, but keep it out of search.
[[redirects]]
  from = "/portal"
  to = "/index.html"
  status = 200

# Anything else: the SPA renders its "page not found" view, with a real 404 status.
[[redirects]]
  from = "/*"
  to = "/index.html"
  status = 404

# ── Security headers ─────────────────────────────────────────────────────────
# CSP: analytics and HubSpot only load after cookie consent (src/lib/consent.js);
# no inline scripts, no eval. 'unsafe-inline' styles are needed for Framer
# Motion and the HubSpot form iframe.

[[headers]]
  for = "/*"
  [headers.values]
    Content-Security-Policy = "${csp}"
    Strict-Transport-Security = "max-age=63072000; includeSubDomains; preload"
    X-Content-Type-Options = "nosniff"
    X-Frame-Options = "SAMEORIGIN"
    Referrer-Policy = "strict-origin-when-cross-origin"
    Permissions-Policy = "camera=(), microphone=(), geolocation=(), payment=(), usb=(), browsing-topics=()"
    Cross-Origin-Opener-Policy = "same-origin-allow-popups"

# ── Caching ──────────────────────────────────────────────────────────────────

[[headers]]
  for = "/assets/*"
  [headers.values]
    Cache-Control = "public, max-age=31536000, immutable"

[[headers]]
  for = "/*.html"
  [headers.values]
    Cache-Control = "public, max-age=0, must-revalidate"

[[headers]]
  for = "/"
  [headers.values]
    Cache-Control = "public, max-age=0, must-revalidate"

[[headers]]
  for = "/media/*"
  [headers.values]
    Cache-Control = "public, max-age=604800"

[[headers]]
  for = "/photos/*"
  [headers.values]
    Cache-Control = "public, max-age=2592000, stale-while-revalidate=86400"

[[headers]]
  for = "/team/*"
  [headers.values]
    Cache-Control = "public, max-age=2592000, stale-while-revalidate=86400"

[[headers]]
  for = "/icons/*"
  [headers.values]
    Cache-Control = "public, max-age=2592000"

[[headers]]
  for = "/manifest.json"
  [headers.values]
    Cache-Control = "public, max-age=86400"

[[headers]]
  for = "/sitemap.xml"
  [headers.values]
    Content-Type = "application/xml; charset=utf-8"
    Cache-Control = "public, max-age=3600"

[[headers]]
  for = "/robots.txt"
  [headers.values]
    Content-Type = "text/plain; charset=utf-8"
    Cache-Control = "public, max-age=3600"
`;
fs.writeFileSync('netlify.toml', toml);
console.log('netlify.toml written,', (rewrites.match(/\[\[redirects\]\]/g) || []).length, 'route rewrites');
